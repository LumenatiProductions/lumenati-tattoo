#!/usr/bin/env node
// Generate components/admin/NavIcon.tsx from the official `ionicons` package —
// same set and same inline-SVG approach as scripts/gen-marketing-icons.mjs, so
// the Command Center rail matches the marketing page and the phone app's
// Ionicons family. Run: node scripts/gen-admin-nav-icons.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SVG = join(root, "node_modules", "ionicons", "dist", "svg");

// nav key -> Ionicons outline file
const MAP = {
  foh: "storefront-outline",
  finances: "logo-usd",
  shopcat: "business-outline",
  admincat: "settings-outline",
  overview: "home-outline",
  mypage: "person-circle-outline",
  bookings: "calendar-outline",
  waitlist: "hourglass-outline",
  clients: "people-outline",
  intake: "document-text-outline",
  followups: "paper-plane-outline",
  social: "share-social-outline",
  healed: "camera-outline",
  qr: "qr-code-outline",
  pnl: "trending-up-outline",
  reports: "bar-chart-outline",
  pay: "wallet-outline",
  goals: "flag-outline",
  rent: "key-outline",
  cash: "cash-outline",
  expenses: "receipt-outline",
  reconcile: "scale-outline",
  artists: "brush-outline",
  artistpages: "globe-outline",
  inventory: "cube-outline",
  compliance: "shield-checkmark-outline",
  staff: "id-card-outline",
  integrations: "link-outline",
  billing: "card-outline",
};

const entries = Object.entries(MAP).map(([name, file]) => {
  const raw = readFileSync(join(SVG, `${file}.svg`), "utf8");
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replaceAll("<title>", "<!--")
    .replaceAll("</title>", "-->")
    .trim();
  return `  ${name}: \`${inner}\`,`;
});

const out = `// GENERATED by scripts/gen-admin-nav-icons.mjs — do not edit by hand.
// Ionicons outline glyphs for the Command Center sidebar.

export type NavIconName = ${Object.keys(MAP)
  .map((k) => `"${k}"`)
  .join(" | ")};

const PATHS: Record<NavIconName, string> = {
${entries.join("\n")}
};

export function NavIcon({ name, className = "" }: { name: NavIconName; className?: string }) {
  return (
    <svg
      viewBox="0 0 512 512"
      className={\`h-4 w-4 shrink-0 \${className}\`}
      fill="currentColor"
      aria-hidden
      dangerouslySetInnerHTML={{ __html: PATHS[name] }}
    />
  );
}
`;

writeFileSync(join(root, "components", "admin", "NavIcon.tsx"), out);
console.log(`NavIcon.tsx written with ${Object.keys(MAP).length} icons`);
